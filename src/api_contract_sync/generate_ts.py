#!/usr/bin/env python3
"""Generate TypeScript types and a typed fetch client from a contract JSON.

Usage:
    python generate_ts.py <contract.json | backend-dir> -o frontend/src/api/generated
           [--only CustomerController,ProductController] [--no-client] [--check]

--check writes nothing and exits 1 if the files in the output directory differ from
what would be generated (use in CI to catch a stale committed client).

Writes three files into the output directory:
  types.ts   - interfaces / enum unions for every contract type, plus
               `<Name>Input` variants for types that are sent as request bodies
  client.ts  - one object per controller (customerApi.listCustomers(), ...)
               on top of a small fetch wrapper; no runtime dependencies
  index.ts   - re-exports both

The files carry a "generated" header. Regenerate rather than hand-editing.
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

HEADER = """/* eslint-disable */
// Generated by api-contract-sync from {backend}
// Do not edit by hand: re-run generate_ts.py after backend changes.
"""

TS_IDENT = re.compile(r"^[A-Za-z_$][\w$]*$")
RESERVED = {"delete", "new", "default", "function", "class", "import", "export", "in", "for", "if", "do", "var",
            "let", "const", "this", "return", "switch", "case", "typeof", "void", "with", "yield", "enum", "await"}


def lower_first(s: str) -> str:
    return s[:1].lower() + s[1:]


def prop_key(name: str) -> str:
    return name if TS_IDENT.match(name) else json.dumps(name)


def member_name(name: str) -> str:
    """Object property name: reserved words are fine here (`orderApi.delete(id)`)."""
    name = re.sub(r"[^\w$]", "_", name)
    return name if TS_IDENT.match(name) else "_" + name


def safe_ident(name: str) -> str:
    """Binding name (const, parameter): reserved words get a trailing underscore."""
    name = member_name(name)
    return name + "_" if name in RESERVED else name


def header(contract: dict) -> str:
    # Only the backend folder's name: an absolute path differs per machine and
    # would make committed generated files show up as changed in CI diffs.
    backend = str(contract.get("backend") or "?").replace("\\", "/").rstrip("/")
    return HEADER.format(backend=backend.rsplit("/", 1)[-1] + "/")


class Gen:
    def __init__(self, contract: dict):
        self.c = contract
        self.types = contract["types"]
        self.input_types: set[str] = set()
        for ep in contract["endpoints"]:
            if ep.get("body"):
                self._collect_inputs(ep["body"]["type"])

    def _collect_inputs(self, t: dict, seen=None) -> None:
        """Types sent as a body get an Input variant (write view of the object)."""
        seen = seen or set()
        k = t.get("kind")
        if k == "ref":
            name = t["name"]
            if name in seen:
                return
            seen.add(name)
            td = self.types.get(name, {})
            if td.get("kind") == "object":
                self.input_types.add(name)
                for p in td["properties"]:
                    self._collect_inputs(p["type"], seen)
            for a in t.get("args", []):
                self._collect_inputs(a, seen)
        elif k in ("array", "page"):
            self._collect_inputs(t["items"], seen)
        elif k == "map":
            self._collect_inputs(t["values"], seen)

    # -------------------------------------------------------------- types
    def ts(self, t: dict, input_view: bool = False) -> str:
        k = t.get("kind")
        if k == "string":
            return "string"  # dates included: JSON carries ISO strings, never Date objects
        if k == "number":
            return "number"
        if k == "boolean":
            return "boolean"
        if k == "void":
            return "void"
        if k == "binary":
            return "Blob"
        if k == "unknown":
            return "unknown"
        if k == "typeParam":
            return t["name"]
        if k == "array":
            inner = self.ts(t["items"], input_view)
            return f"({inner})[]" if re.search(r"[|& ]", inner) else f"{inner}[]"
        if k == "map":
            return f"Record<string, {self.ts(t['values'], input_view)}>"
        if k == "page":
            return f"SpringPage<{self.ts(t['items'], input_view)}>"
        if k == "ref":
            name = t["name"]
            if input_view and name in self.input_types:
                name = f"{name}Input"
            args = t.get("args")
            return name + (f"<{', '.join(self.ts(a, input_view) for a in args)}>" if args else "")
        return "unknown"

    def doc(self, text: str | None, indent: str = "") -> list[str]:
        if not text:
            return []
        text = text.replace("*/", "* /")
        if len(text) > 300:
            text = text[:297].rsplit(" ", 1)[0] + "..."
        return [f"{indent}/** {text} */"]

    def type_decl(self, name: str, td: dict) -> list[str]:
        out = self.doc(td.get("doc"))
        if td["kind"] == "enum":
            vals = " | ".join(json.dumps(v) for v in td["values"]) or "never"
            out.append(f"export type {name} = {vals};")
            out.append(f"export const {name}Values = [{', '.join(json.dumps(v) for v in td['values'])}] as const;")
            return out
        tp = f"<{', '.join(td['typeParams'])}>" if td.get("typeParams") else ""
        out.append(f"export interface {name}{tp} {{")
        for p in td["properties"]:
            if p.get("writeOnly"):
                continue
            out += self.doc(p.get("doc"), "  ")
            null = " | null" if p["nullable"] else ""
            ro = "readonly " if p.get("readOnly") else ""
            out.append(f"  {ro}{prop_key(p['name'])}: {self.ts(p['type'])}{null};")
        out.append("}")
        if name in self.input_types:
            out.append("")
            out.append(f"/** Request-body shape of {name}: server-generated and read-only fields are optional or omitted. */")
            out.append(f"export interface {name}Input{tp} {{")
            for p in td["properties"]:
                if p.get("readOnly"):
                    continue
                optional = p["nullable"] or p.get("generated")
                null = " | null" if p["nullable"] or p.get("generated") else ""
                out.append(f"  {prop_key(p['name'])}{'?' if optional else ''}: {self.ts(p['type'], True)}{null};")
            out.append("}")
        return out

    def types_ts(self) -> str:
        lines = [header(self.c).rstrip(), ""]
        if any('"page"' in json.dumps(v) for v in [self.c["endpoints"], self.types]):
            lines += [
                "/** Spring Data Page<T> as serialized by Jackson. */",
                "export interface SpringPage<T> {",
                "  content: T[];",
                "  totalElements: number;",
                "  totalPages: number;",
                "  number: number;",
                "  size: number;",
                "  first: boolean;",
                "  last: boolean;",
                "  empty: boolean;",
                "}",
                "",
            ]
        for name, td in self.types.items():
            lines += self.type_decl(name, td)
            lines.append("")
        return "\n".join(lines).rstrip() + "\n"

    # -------------------------------------------------------------- client
    def client_ts(self, only: set[str] | None) -> str:
        eps = [e for e in self.c["endpoints"] if not only or e["controller"] in only]
        groups: dict[str, list[dict]] = {}
        for e in eps:
            groups.setdefault(e["controller"], []).append(e)

        body_lines = []
        imports: set[str] = set()
        for ctl, items in groups.items():
            obj = lower_first(re.sub(r"Controller$", "", ctl)) + "Api"
            body_lines.append(f"/** {ctl} */")
            body_lines.append(f"export const {safe_ident(obj)} = {{")
            names: dict[str, int] = {}
            for e in items:
                fn = e["operation"]
                names[fn] = names.get(fn, 0) + 1
                if names[fn] > 1:
                    fn = f"{fn}{names[fn]}"
                body_lines += self.client_fn(e, member_name(fn), imports)
            body_lines.append("};")
            body_lines.append("")

        type_imports = sorted(i for i in imports if i in self.types or i.endswith("Input") or i == "SpringPage")
        lines = [header(self.c).rstrip(), ""]
        if type_imports:
            lines.append("import type {")
            lines += [f"  {i}," for i in type_imports]
            lines.append("} from './types';")
            lines.append("")
        lines += RUNTIME.strip("\n").splitlines()
        lines.append("")
        lines += body_lines
        return "\n".join(lines).rstrip() + "\n"

    def _imports_of(self, t: dict, input_view: bool, acc: set[str]) -> None:
        k = t.get("kind")
        if k == "ref":
            name = t["name"]
            acc.add(f"{name}Input" if input_view and name in self.input_types else name)
            for a in t.get("args", []):
                self._imports_of(a, input_view, acc)
        elif k == "page":
            acc.add("SpringPage")
            self._imports_of(t["items"], input_view, acc)
        elif k == "array":
            self._imports_of(t["items"], input_view, acc)
        elif k == "map":
            self._imports_of(t["values"], input_view, acc)

    def client_fn(self, e: dict, fn: str, imports: set[str]) -> list[str]:
        args, path = [], e["path"]
        used_args: set[str] = set()
        for pp in e["pathParams"]:
            a = safe_ident(pp["name"])
            used_args.add(a)
            args.append(f"{a}: {self.ts(pp['type'])}")
            self._imports_of(pp["type"], False, imports)
        path_expr = re.sub(
            r"\{([^}:]+)(?::[^}]*)?\}",
            lambda m: "${encodeURIComponent(String(" + safe_ident(m.group(1)) + "))}",
            path,
        )
        path_expr = "`" + path_expr + "`" if "${" in path_expr else json.dumps(path_expr)
        opts = []
        body = e.get("body")
        if body:
            if body.get("contentType") == "multipart":
                args.append(f"body{'' if body['required'] else '?'}: FormData")
                opts.append("body, multipart: true")
            else:
                bt = self.ts(body["type"], True)
                self._imports_of(body["type"], True, imports)
                args.append(f"body{'' if body['required'] else '?'}: {bt}")
                opts.append("body")
        qp = [q for q in e["queryParams"] if not (body and body.get("contentType") == "multipart" and q["type"]["kind"] in ("binary", "array"))]
        if qp:
            fields, any_required = [], False
            for q in qp:
                if q["name"] == "*":
                    if q.get("modelAttribute"):
                        t = self.ts(q["type"])
                        self._imports_of(q["type"], False, imports)
                        fields.append(f"...Partial<{t}>")
                    else:
                        fields.append("[key: string]: string | number | boolean | undefined")
                    continue
                any_required |= q["required"]
                self._imports_of(q["type"], False, imports)
                d = f" /* default {q['default']} */" if q.get("default") else ""
                fields.append(f"{prop_key(q['name'])}{'' if q['required'] else '?'}: {self.ts(q['type'])}{d}")
            spread = [f for f in fields if f.startswith("...")]
            plain = [f for f in fields if not f.startswith("...")]
            qt = "{ " + "; ".join(plain) + " }" if plain else "{}"
            if spread:
                qt = " & ".join([qt] + [f[3:] for f in spread]) if plain else " & ".join(f[3:] for f in spread)
            args.append(f"query{'' if any_required else '?'}: {qt}")
            opts.append("query")
        args.append("init?: RequestInit")
        opts.append("init")
        rt = self.ts(e["response"]["type"])
        self._imports_of(e["response"]["type"], False, imports)
        if e["response"].get("nullable"):
            rt += " | null"
        fmt = e["response"]["format"]
        if fmt == "binary":
            rt = "Blob"
        elif fmt == "text":
            rt = "string"
        elif fmt == "none":
            rt = "void"
        lines = []
        meta = f"{e['method']} {e['path']}"
        if e.get("auth"):
            meta += f" — auth: {e['auth']}"
        summary_line = re.split(r"(?<=\.)\s", e.get("doc") or "", maxsplit=1)[0][:160].replace("*/", "* /")
        lines.append(f"  /** {meta}{' — ' + summary_line if summary_line else ''} */")
        lines.append(f"  {fn}: ({', '.join(args)}): Promise<{rt}> =>")
        lines.append(f"    request<{rt}>({json.dumps(e['method'])}, {path_expr}, {{ {', '.join(opts)}, response: {json.dumps(fmt)} }}),")
        return lines


RUNTIME = r"""
export interface ApiConfig {
  /** Prepended to every path, e.g. "" when the SPA is served by Spring, or "http://localhost:8080". */
  baseUrl: string;
  /** Sent on every request; "include" keeps the Spring session cookie. */
  credentials: RequestCredentials;
  /** Extra headers for every request (e.g. an Authorization header). */
  headers: Record<string, string> | (() => Record<string, string>);
  fetch: typeof fetch;
}

export const apiConfig: ApiConfig = {
  baseUrl: '',
  credentials: 'include',
  headers: {},
  fetch: (...args) => fetch(...args),
};

export function configureApi(overrides: Partial<ApiConfig>): void {
  Object.assign(apiConfig, overrides);
}

/** Thrown for any non-2xx response; `message` comes from Spring's error body when present. */
export class ApiError extends Error {
  constructor(
    readonly status: number,
    message: string,
    readonly body: unknown,
  ) {
    super(message);
    this.name = 'ApiError';
  }
}

type Query = Record<string, unknown>;

interface RequestOptions {
  query?: Query;
  body?: unknown;
  multipart?: boolean;
  response: 'json' | 'text' | 'binary' | 'none';
  init?: RequestInit;
}

function buildQuery(query?: Query): string {
  if (!query) return '';
  const params = new URLSearchParams();
  for (const [key, value] of Object.entries(query)) {
    if (value === undefined || value === null) continue;
    for (const item of Array.isArray(value) ? value : [value]) params.append(key, String(item));
  }
  const text = params.toString();
  return text ? `?${text}` : '';
}

async function request<T>(method: string, path: string, opts: RequestOptions): Promise<T> {
  const extra = typeof apiConfig.headers === 'function' ? apiConfig.headers() : apiConfig.headers;
  const headers: Record<string, string> = { Accept: 'application/json, text/plain, */*', ...extra };
  let body: BodyInit | undefined;
  if (opts.body !== undefined) {
    if (opts.multipart) {
      body = opts.body as FormData;
    } else {
      headers['Content-Type'] = 'application/json';
      body = JSON.stringify(opts.body);
    }
  }
  const response = await apiConfig.fetch(apiConfig.baseUrl + path + buildQuery(opts.query), {
    method,
    credentials: apiConfig.credentials,
    ...opts.init,
    headers: { ...headers, ...(opts.init?.headers as Record<string, string> | undefined) },
    body,
  });
  if (!response.ok) {
    let data: unknown = null;
    let message = `${method} ${path} failed with ${response.status}`;
    try {
      data = await response.json();
      const d = data as { message?: string; error?: string; detail?: string };
      message = d.message || d.detail || d.error || message;
    } catch {
      /* non-JSON error body */
    }
    throw new ApiError(response.status, message, data);
  }
  if (opts.response === 'none' || response.status === 204) return undefined as T;
  if (opts.response === 'binary') return (await response.blob()) as T;
  if (opts.response === 'text') return (await response.text()) as T;
  const text = await response.text();
  return (text ? JSON.parse(text) : null) as T;
}
"""


def render(contract: dict, only: set[str] | None = None, client: bool = True) -> dict[str, str]:
    """File name -> content for everything the generator writes."""
    g = Gen(contract)
    files = {"types.ts": g.types_ts()}
    if client:
        files["client.ts"] = g.client_ts(only)
    idx = ["export * from './types';"] + (["export * from './client';"] if client else [])
    files["index.ts"] = header(contract) + "\n".join(idx) + "\n"
    return files


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("contract", type=Path, help="contract JSON from extract_spring.py, or the backend directory itself")
    ap.add_argument("-o", "--out", type=Path, required=True, help="output directory (created if missing)")
    ap.add_argument("--only", help="comma-separated controller names to include in client.ts")
    ap.add_argument("--no-client", action="store_true", help="only write types.ts")
    ap.add_argument("--check", action="store_true", help="write nothing; exit 1 if the output directory is stale")
    ext = ap.add_argument_group("when the first argument is a backend directory (extract on the fly)")
    ext.add_argument("--context-path", default=None)
    ext.add_argument("--bigdecimal", choices=["number", "string"], default=None)
    ext.add_argument("--naming", choices=["camel", "snake", "kebab", "lower", "upper_camel"], default=None)
    a = ap.parse_args(argv)
    if not a.contract.exists():
        ap.error(f"{a.contract} does not exist")
    if a.contract.is_dir():
        try:
            from .extract_spring import build_contract
        except ImportError:
            sys.path.insert(0, str(Path(__file__).resolve().parent))
            from extract_spring import build_contract  # noqa: E402
        contract = build_contract(a.contract, a.bigdecimal, a.context_path, a.naming)
    else:
        contract = json.loads(a.contract.read_text(encoding="utf-8"))
    files = render(contract, set(a.only.split(",")) if a.only else None, not a.no_client)

    if a.check:
        # Compare ignoring line endings: git may check files out with CRLF on Windows.
        def norm(p: Path):
            return p.read_text(encoding="utf-8").replace("\r\n", "\n") if p.exists() else None
        stale = [n for n, text in files.items() if norm(a.out / n) != text]
        if stale:
            print(f"{a.out}: out of date ({', '.join(stale)}). Regenerate with the same command without --check.",
                  file=sys.stderr)
            return 1
        print(f"{a.out}: up to date", file=sys.stderr)
        return 0

    a.out.mkdir(parents=True, exist_ok=True)
    for name, text in files.items():
        # LF on every OS, so --check and git diffs agree (Path.write_text has no newline= before 3.10).
        with open(a.out / name, "w", encoding="utf-8", newline="\n") as fh:
            fh.write(text)
    print(f"Wrote {', '.join(files)} to {a.out} "
          f"({len(contract['types'])} types, {len(contract['endpoints'])} endpoints)", file=sys.stderr)
    return 0


if __name__ == "__main__":
    sys.exit(main())
